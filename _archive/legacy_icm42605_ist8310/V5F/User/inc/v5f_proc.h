/* =====================================================================
 * 处理链（V5F 大核侧数据加工）
 *   DMA1_Channel2_IRQHandler 的"主任务区"每帧依次调用本文件的处理函数：
 *     1) 输入从 g_v5f_hold 里取（如 h->imu.gyro_lsb[]）；
 *     2) 结果直接写回 g_v5f_hold 的对应字段；
 *     3) 每个函数必须置自己的结果有效性标志；
 *     4) 返回 0 = 正常，非 0 = 异常（主任务区锁存错误码，不打断后续函数）。
 *   处理函数只允许被该中断单线程调用（无锁，状态为文件静态）。
 *   inc/ 放本头文件与各函数原型，src/ 放各函数实现（一函数一 .c）。
 * ===================================================================== */

/* ---------------- 处理链内部的门控（处理函数之间传递状态） ----------------
 * 实例 g_v5f_proc_gate 定义在 SPI_rx.c。
 * 写-读方向恒为"**后面的步骤写、前面的步骤下一帧读**"：
 *   处理函数 2（动静判定）      写 is_static -> 处理函数 1（陀螺零偏牵引）下一帧读
 *   处理函数 5（加速度外部门控） 写 acc_traction -> 处理函数 4（加速度零偏牵引）下一帧读
 *                               写 att_tilt     -> 处理函数 3（重力/倾斜融合）下一帧读
 * 每帧的判定都用本帧已完成的、零偏校准后的原始传感器值；依赖关系单向。
 *
 * ★★ 铁律：**每一条牵引 / 融合都必须由外部门控驱动，且一一对应** ——
 *    A 环的门不能拿去门 B，门也绝不允许在环内部现算。两条都是踩过的坑：
 *      · 自引用：门用环自己正在更新的状态 -> 未收敛时锁死。实测 20260914_044158：
 *        b_a 顶到钳位后 |a_lin| 恒大于 ON，门再也打不开，速度按 0.35 m/s^2 线性发散。
 *      · 交叉门控：A 的门因 B 的状态而关，而 B 恰恰是唯一能救 A 的那个环。实测
 *        20260914_061955：姿态歪 6.725 deg -> 加速度牵引门判据 |w|=107 mg > OFF
 *        -> acc_traction = 0 -> **倾斜融合被同一个门关掉** -> 姿态永远回不来，
 *        |a_lin| 卡在 117 mg（= 1.15 m/s^2 的速度误差）。
 *    所以：一个环一个字段；每个字段的判据只依赖"本帧原始传感器值 + 离线标定常量"。
 *    ★ 新增任何牵引 / 融合时，必须同步：① 在此结构加字段；② 由一个**下游**处理
 *      函数写它；③ 在 SPI_rx.c 的 justfloat_report 里加一条上报通道。
 *
 *   is_static             1 = 静止（陀螺零偏牵引按 τ_work = 12 s 收敛），
 *                         0 = 运动（冻结 + 按 rollback_granules 回退）
 *   rollback_granules     静止→运动边沿时回退的 20 ms 粒度数（= 24 格 = 480 ms）
 *   acc_traction          1 = **加速度零偏牵引**运行，0 = 冻结（判据 |w|，见 proc_acc_gate.c）
 *   acc_rollback_granules 加速度牵引 牵引→冻结边沿时回退的 20 ms 粒度数（= 1 格 = 20 ms）
 *   att_tilt              1 = **重力/倾斜融合**运行，0 = 冻结（判据 |off| 在 1 g ±5%
 *                         且陀螺判静，见 proc_acc_gate.c）。它与 acc_traction 判据不同：
 *                         对"姿态歪"完全免疫，所以不会被姿态误差关掉。 */
typedef struct {
    volatile uint8_t is_static;
    volatile uint8_t rollback_granules;
    volatile uint8_t acc_traction;
    volatile uint8_t acc_rollback_granules;
    /* 门B：1 = 重力/倾斜融合开。判据 = 256 ms 窗内 |off| 均值落在 1 g +-3%
     *      （V5F_ATT_TILT_ALIM_* / V5F_ATT_TILT_GRAN*NGRAN），
     *      且同一窗内**离线常量校正后**角速度的净均值 |w| < V5F_ATT_TILT_LEV_DPS。
     *      不含 is_static：实测手持静止 is_static 仅 10%，而比力方向与陀螺积分
     *      重力方向夹角中位数 0.49 deg。净 |w| 条件是为了挡住"转正方形"这类
     *      真转动（见 v5f_tune.h 的判据落地 v2 记录）。 */
    volatile uint8_t att_tilt;
    volatile uint8_t vel_soft;    /* **速度的软 ZUPT 置信度**，0..255 连续值（不是 0/1 门）。
                                   * 由处理函数 5（下游）算，处理函数 6 下一帧读。
                                   * 速度那边用它调衰减**速率**；衰减时刻都在跑，
                                   * 所以这个字段不会把衰减"关掉"，只会改变多快。 */
    /* ===== EKF 的七道门（第 8 步 v5f_proc_ekf_gate **下游**写，第 7 步
     *       v5f_proc_ekf **下一帧**读）。与上面几条同一纪律，一字不改：
     *         · 一环一门：每道门只门一个观测，改一个不动另一个；
     *         · 判据只用**外生量**（原始 LSB、离线常量、stat、acc_valid、
     *           mag.trust、GPS 报文质量字段），绝不取滤波器自己的输出；
     *         · 门的"物理可用性"与内层新息 chi2 的"野值剔除"是两件事，
     *           chi2 在第 7 步算并单独记进 gate_bits 的 bit9。
     *   ekf_gps_pos  fixq>=1 + 星数 + HDOP + C/N0 + RMC/GGA 有效位
     *   ekf_gps_alt  同上且 VDOP 合格 + GGA 高度位
     *   ekf_baro     上电预热满 5 s + 温度合理 + 未饱和
     *   ekf_gps_vel  同上且**原始** speed > 0.4 m/s（低速时 course 无意义）
     *   ekf_zupt     is_static + |a_lin| < 0.05 g + 原始 GPS 速度 < 0.5 m/s
     *                （只用 is_static 不行：等效原理下匀速平动对它不可见）
     *   ekf_tilt     | |a| - 1 | < 3% + 长窗净 |w| 小（或启动旁路），独立字段
     *   ekf_mag_yaw  只用 mag.trust（已含 |y| 模长门与 |a_lin| 倾斜门） */
    volatile uint8_t ekf_gps_pos;
    volatile uint8_t ekf_gps_alt;
    volatile uint8_t ekf_baro;
    volatile uint8_t ekf_gps_vel;
    volatile uint8_t ekf_zupt;
    volatile uint8_t ekf_tilt;
    volatile uint8_t ekf_mag_yaw;
    volatile uint8_t _rsv_ekf;
} v5f_proc_gate_t;

extern volatile v5f_proc_gate_t g_v5f_proc_gate;   /* 门控实例（SPI_rx.c 定义） */

