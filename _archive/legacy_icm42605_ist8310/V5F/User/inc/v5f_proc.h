/* ---------------- 加速度牵引的**外部门控**（处理函数 5） ----------------
 * 与陀螺门**同构**：陀螺门问"零偏校正后的角速度是不是接近 0"，这里问
 * "**去掉重力分量后的加速度是不是接近 0**"。
 *   判据量 a_lin = accel_g - R(q)^T * up_ref（零偏已校准，单位 g），
 *   由处理函数 4 每帧无条件算出并发布（h->imu.a_lin[]）。
 *
 * 为什么这样不会自锁：牵引的任务就是把 a_lin 驱到 0，所以"a_lin 接近 0"正是这个
 *   环的稳定不动点。陀螺门是同一结构 —— is_static 也是从**校正后**的 gyro_dps 算的。
 *   实测（20260914_042240，设备静止）：|a_lin| 中位 9.4 mg、90% 19.3 mg、最大 112 mg；
 *   而同一段里陀螺统计量 level 中位 0.85 dps、远超它自己的门槛，所以陀螺门整段关闭、
 *   零偏被冻死在标定初值上（30 s 只动了 0.9 mg），速度按残余 a_lin 线性漂。
 *
 * 顺序语义与陀螺门一致：**快冻结、慢恢复** —— 真实机动在 1 ms 内冻结牵引，
 *   恢复要连续 100 ms 都接近 0（避免机动过程中的抖动把牵引重新打开）。
 *
 * ★ 锁死条件与钳位的关系（必须一起满足）：
 *   门能重新打开的前提是真静止时 |a_lin| 能回到 ON 以下，而 a_lin ≈ 泄露 - b_a偏差，
 *   所以 sqrt(3)*零偏钳位 + |泄露| 必须 < ALIN_ON。零偏钳位见 V5F_ACC_TRACTION_BIAS_LIM_MG。 */
/* 冻结边沿的回退粒度。
 * ★ 必须按**本门自己的检测延迟**定，绝不能照抄陀螺门的 24 格（480 ms）：
 *   陀螺那 24 格是对着它实测 0.46 s 的检测延迟定的（见 proc_static_detect.c），
 *   而本门 DEB_OFF = 8 帧 = 1 ms 就冻结，误牵引连一格（20 ms）都不到。
 *   拿 480 ms 回退，每次关门丢掉 24 格 —— 机动一多门一翻，开门时间会被回退全部吃回去，
 *   门开 90% 也等于没开（有效牵引时间必须 >= 需求时间才能收敛）。
 *   快照粒度就是 20 ms，所以最小可用回退 = 1 格 = 20 ms；一次关门只损失 20 ms
 *   （相对 tau_p = 14 s 只有 0.14%），有效牵引时间 ≈ 开门时间。
 *   若要把回退彻底关掉，把这里改成 0u 即可（at_rollback 会跳过）。 */


/* 外部降权接口：上位控制器在"水平机动"期间把它写 0（或 0~1 之间的值），
 * 牵引权重整体乘上它。为什么必须靠外部信号：|a|-1g 对**水平**加速度只有二阶敏感
 * （a_h = 1 m/s^2 时仅 0.48 mg），光靠加速度计分不开"倾斜"和"水平机动"；
 * 而水平机动发生时上位控制器一定有指令，用它是最干净的判据。
 * 初值 1.0 = 不降权。本文件只读、不改。 */
extern volatile float g_v5f_acc_traction_wext;

/* ---------------- 世界系速度（处理函数 5） ----------------
 *   a_nav = G_local * ( R(q) * accel_g - up_ref )      导航系线加速度 [m/s^2]
 *   v    += a_nav * dt ;  判静时 v = 0（ZUPT，速度环在这里闭合）
 *   G_local 用本地重力：重力项是 1 g 量级，G 差 0.1% 就留 1 mg 残差（= 0.01 m/s^2），
 *   而 1 mg 正是零偏牵引的收敛目标量级，所以这个数要和上位机分析用的保持一致。 */
/* ---------------- 重力方向持续测量（处理函数 3，Mahony 式倾斜修正） ----------------
 * 启动时处理函数 3 用重力**一次性**把导航系定成竖直（att_init_from_gravity，见该文件）；
 * 之后每帧用加速度计测到的重力方向持续牵引姿态：
 *   a_hat = accel_g / |accel_g|        加速度计测到的"上"（机体系，带着零偏 beta）
 *   g_hat = R(q)^T * up_ref            姿态估计的"上"（机体系）
 *   e     = a_hat x g_hat              误差（对齐时为 0）
 *   omega_tilt = +K * e                叠加到四元数积分角速度上
 * 符号由数值验证：K 取 +1/tau 时 2/17/60 deg 初倾角全部收敛到 ~0.001 deg；
 *   取负号则发散到 180 deg。
 *
 * ★ 本环是**纯 P 环**，对常值速率扰动（残余陀螺零偏 omega_res）必然留稳态误差。
 *   闭环里它与加速度零偏牵引环并联作用于同一个 a_lin，两条路一起把 a_lin 拉向 0：
 *     da_lin/dt = -a_lin/tau_tilt - a_lin/tau_p
 *   => tau_eff = 1/(1/tau_tilt + 1/tau_p)
 *   平衡时姿态被残余零偏顶在一个固定倾角上，而这个倾角直接漏重力进 a_lin：
 *     tilt_eq = omega_res * tau_eff
 *   实测（20260914_060222_791，末段 3.86 s is_static 100%）：
 *     omega_res（gyro_dps 水平直流）= 0.014742 dps = 53 deg/h
 *     tau_tilt=30 -> tau_eff=9.53 s -> tilt_eq=0.140 deg，实测 R(q)*u 偏竖直 0.164 deg (对上)
 *     同时 a_lin 水平分量 2.2 mg，与这个倾角的漏重力一致
 *   => tau_tilt 每降一档，tilt_eq 按 tau_eff 等比下降：
 *     tau_tilt | tau_eff | tilt_eq @53 deg/h | 备注
 *     ---------+---------+-------------------+------------------------------
 *        3 s   | 2.47 s  |      0.036 deg    | 再快就开始跟随加速度计零偏
 *        5 s   | 3.68 s  |      0.054 deg    | ★ 当前取值
 *       10 s   | 5.83 s  |      0.086 deg    |
 *       30 s   | 9.53 s  |      0.140 deg    | 实测 0.164 deg，偏大
 *   下限由另一边定：tau_tilt 越小，姿态越被**带零偏、还被线加速度污染**的加速度计牵着
 *   走；极端情况（tau_tilt << tau_p）姿态会被拉到 beta/g 的倾角上 —— 那正是零偏牵引环
 *   要消掉的量，两个环互顶。取 5 s：tilt_eq 降到 30 s 档的 0.39 倍，仍远慢于 tau_p。
 *
 * ★ omega_res 本身由陀螺零偏牵引环收敛（tau_work = 12 s，长期优秀值，不要动）。
 *   零偏的**真值以在线追踪值为准** —— 它已经把器件个体差异和温度都吸收了；离线常量
 *   （GB_BIAS0_LSB）只是帮上电收敛的通用值，实测偏差可达 100 deg/h 量级
 *   （060222：x +125 / y +82 / z -134 deg/h），这是**设计预期，不是故障**。
 *   所以上电后 omega_res 先大后小、tilt_eq 随之下降；tau_tilt 的作用就是保证在这个
 *   下降过程里倾角不要把 a_lin 顶得太高。
 *
 * 门控：只在"加速度计只剩重力"时修正（复用 gate->acc_traction，本帧读的是它上一帧的
 *   判定）。机动期间冻结 —— 与零偏牵引同一条原则。 */
/* ★ 两段 τ：启动段 tau_boot = 1 s（与陀螺零偏牵引的启动段同值），
 *   累计静止满 3*tau_boot = 3 s（= h->imu.bias_ok 置位）后切到工作段 5 s。
 *   为什么启动段要快：导航系刚由重力定出来，此时残余零偏最大（离线常量偏差实测
 *   可达 125 deg/h），要用硬牵引在**几秒内**把四元数拉对齐重力系；之后放松，
 *   免得长期跟着加速度计的零偏走。
 *   启动段的并联时间常数 tau_eff = 1/(1/1 + 1/7) = 0.875 s
 *   （与加速度牵引启动段 tau_p_boot = 7 s 并联），即上电后几秒内完成对齐。
 *   切换用 h->imu.bias_ok（陀螺零偏牵引的"累计静止满 3*tau_boot"锁存），
 *   与那两条环同一判据，不引入新的计时器。 */
/* 系数：om_tilt[dps] = K * e，e = |a_hat x g_hat| 是**弧度**（无量纲）。
 * ★ 注意 w 是**速率**（dps），不是增量 —— dt 由 proc_attitude.c 里统一的 half 乘，
 *   所以这里绝不能折进 tick 或 dt，否则会小 1/dt 倍（约 8000 倍）等于不修正。
 * K = (180/pi)/tau；工作段 57.29578/5 = 11.45916 dps/rad、启动段 57.29578/1 = 57.29578。
 * 自检：2 deg 残余 -> e = 0.0349 -> 工作段修正率 0.400 dps、启动段 2.000 dps
 *       （分别与 2/5、2/1 deg/s 一致）。 */

/* 倾斜融合的**专用外部门控**字段 gate->att_tilt（**不用 gate->acc_traction**，也不在
 * 环内现算）—— 由 proc_acc_gate.c 独立算出：
 *   h->stat.is_static（陀螺判静）+ |off| 落在 [LO, HI] 内，
 *   其中 off = (accel_lsb - 离线标定零偏) / 标度，即"用离线常量换算的比力"。
 * ★ 为什么用"比力模长"而不是"残余矢量 w"：姿态歪了会让 w 变大（实测 6.7 deg 对应
 *   107 mg），于是那个门把倾斜环关掉，而倾斜环正是唯一能纠正姿态的东西 —— 死锁。
 *   模长对姿态歪完全免疫（歪只改方向不改模长），只对线加速度敏感。
 * ±5% 的取法：水平线加速度 a_h 只把模长抬高 a_h^2/2g（二阶），a_h = 1 m/s^2 时仅
 *   0.48 mg，所以这个门挡不住水平平动 —— 由 gate->is_static 挡（平动时陀螺判运动）。
 *   真正的匀速平动两个门都挡不住，那是等效原理的盲点，靠外部降权接口处理。 */

/* ---------------- 世界系速度：时刻向 0 衰减（漏积分器） ----------------
 * 不做任何"速度归零门"。原门要 stat.is_static（陀螺统计量 < 0.065~0.195 dps），
 * 而本机环境 level 中位 0.6~0.9 dps，远超门槛 —— 实测 20260914_050043 的
 * t=20~28 s 里 is_static 全程 0%，于是速度冻在 0.055~0.073 m/s 不动。
 *
 * ★★ 衰减必须"时刻"执行：放在 proc_velocity.c 的**第一条**语句，先于冻结门
 *    和所有 dt 早退。挂在门后 = 门一挡就完全不衰减，那还是"有门控的衰减"，
 *    速度会挂在某个值上不下来 —— 正是要消掉的行为。
 *
 * 递推：  v += a_nav * dt  ；  v 按**常速率**缩短 |v|（见下）
 *
 * ★★ 用**常速率（线性）衰减**，不是乘性漏积分器。两者的差别是本质的：
 *     乘性 v *= (1 - dt/tau)：本帧减掉的**量** = |v|*dt/tau，**正比于 |v|**。
 *         · 大速度漏得多、小速度漏得少 -> 一次"推出去再拉回来"（净冲量 0）的正向
 *           摆幅被按比例吃掉，反向那一半没被同等对待 -> **速度穿过 0 继续反相**。
 *           实测（20260914_062704，τ_v=1 s）反相幅度达峰值的 23.3%。
 *         · 偏置稳态停在 a_bias*tau != 0 -> 平台。
 *     常速率 v -= K*dt*unit(v)：本帧减掉的**量**恒为 K*dt，**与 |v| 无关**。
 *         · 大速度（真实运动）相对损失极小 -> 正反两半被同等对待 -> 反相基本消失；
 *         · |v| < K*dt 时一帧减完、**精确归零**；且只要 |a_bias| < K，稳态就是**精确 0**
 *           （不是 a_bias*tau）—— 平台被彻底消掉，而不是封顶。
 *     ★ 这不是门控：它是衰减器的**不动点**，每帧无条件执行，与冻结门/时间戳早退无关。
 *       零速附近也没有抖动：减到 0 就停住，不会来回抖。
 *
 * 定标（同一段实测驱动 20260914_062704 重放；末段 a_nav 直流 = 0.0221 m/s^2 = 2.26 mg）：
 *   K (m/s^2) | = mg | 反相/峰值 | |v|max | 末段 |v| 均值
 *   ----------+------+-----------+--------+-------------
 *     0.020   | 2.04 |   0.041   | 0.469  |   0.093
 *     0.030   | 3.06 |   0.056   | 0.469  |   0.055
 *     0.050   | 5.10 |   0.088   | 0.474  |   0.011    <- 取值
 *     0.100   |10.21 |   0.166   | 0.475  |   0.002
 *   对照（乘性）：tau_v=1 s -> 反相 0.233、|v|max 0.429、末段 0.0279；
 *                 tau_v=3 s -> 反相 0.092、|v|max 0.464、末段 0.0704
 *   即 K=0.05 在"同等反相"下漂移小 6.6 倍，在"同等漂移"下反相小 2.6 倍，运动保真还更好。
 *   取 K = 0.05 的余量依据：末段实测偏置 0.0221 m/s^2，K 留 2.3 倍余量；
 *   代价是真实运动每秒损失 K*T（1 s 机动损失 0.05 m/s，相对 0.4 m/s 峰值约 12%）。
 * ★ 它只能消掉**小于 K 的**偏置；要彻底消除漂移仍须把 a_bias 本身收敛掉。 */

/* 写 h->imu.acc_traction_flags，每帧重算（非 0 返回时保持 0） */
#define V5F_ACC_TRACTION_FLAG_ROLLBACK  0x01u   /* 本帧发生了零偏回退 */

/* ---------------- 处理函数 2（动静判定）：阈值查找表 ----------------
 * 统计量 s = max_axis |W 帧滑窗均值|，其噪声尺度 sigma_s = sigma_raw/sqrt(W)
 *   = 0.1224/sqrt(128) = 0.01082 dps（实测 sigma_raw = 0.1224 dps，三轴平均）。
 * 严谨判据：s 的不确定度有两项 —— 窗内速率噪声 sigma_s，以及"标定初值残差"
 *   e(T) = e0 * exp(-T/tau)，T = 已累积的静止证据（粒度数）。
 *   sigma_eff(T) = sqrt(sigma_s^2 + e(T)^2)
 * 维持同一虚警预算 K=10 就需要 thr(T) = clamp(K*sigma_eff(T), base, 3*base)：
 *   证据不足时抬高阈值，等 e(T) 衰减进噪声后落回 base。
 * 上限 = 3*base = 30 sigma_s = 0.3246 dps：设计 e0 = 0.083 dps 使该上限正好覆盖
 *   启动前 12 s（前 5 档），此后按判据衰减，约 50 s 落到 base。
 *   实测会话间初值散布 ~0.037 dps、观测到的冷启动残差 ~0.02 dps，30 sigma 平台
 *   在 0.1% 口径下可容忍初值误差到 ~0.29 dps（= 0.3246 - 3.29*sigma_s），余量 8x。
 * 表离线算好（build_thr_table.py），固件只做"移位取档 + 查表 + 比较"，
 *   不做 exp/sqrt 等运行时现算。索引 = bias_evidence_gran >> V5F_DET_THR_SHIFT。 */
/* 回退粒度：24 格 x 20 ms = 480 ms —— 实测本机典型转动（峰值 100 dps）的检测延迟
 * 0.46 s，24 格正好覆盖；仿真扫 N 的结论见 rollback_sim.py / rollback_sizing.py */

/* ==================== 处理函数原型 ==================== */

/* 1) 陀螺零偏校正
 *    out[i] = (gyro_lsb[i] - bias[i]) / g_v5f_gyro_lsb_per_dps[i]   （°/s，逐轴标度）
 *    bias 初值：标定常量（见 proc_gyro_bias.c 的 GB_BIAS0_*），上电即在零点附近；
 *    bias 估计：静止时一阶牵引向 gyro_lsb（期望校正输出为 0），运动时冻结；
 *          τ 分两段：启动段 τ_boot = 1 s（快速吃掉上电初值残差 e0），
 *          累计静止满 3τ_boot = 3 s 后切工作段 τ_work = 12 s 并锁存 bias_ok；
 *          切换判据是"累计静止时长"而非上电时间（一动就冻结，自然不会误切）。
 *    回溯：内部按 20 ms 粒度存 64 份 bias 快照（1.28 s），门控告知"静止→运动"
 *          边沿时回退 gate->rollback_granules 个粒度（取该粒度快照作为新起点继续牵引），
 *          并钳位到本段静止已有的粒度数。
 *    结果字段：h->imu.gyro_dps[] / gyro_bias_dps[] / corr_valid / bias_ok / corr_flags
 *    bias_ok：累计静止 ≥ 3τ_boot（3 s）后锁存为 1，回退不清除；处理函数 3 用它做使能门。
 *    正常返回时 corr_valid = 1；非 0 返回时 corr_valid = 0（结果字段不保证已更新）。 */
uint8_t v5f_proc_gyro_bias(volatile v5f_hold_t *h, const volatile v5f_proc_gate_t *gate);

/* 2) 动静判定（后验，吃前一项的结果）
 *    输入 h->imu.gyro_dps[]（上一步的校正输出），统计量 s = max_axis |W 帧滑窗均值|；
 *    s > THR_ON 连续 DEB_ON 帧判运动，s < THR_OFF 连续 DEB_OFF 帧判静止（滞回+防抖）。
 *    结果字段：h->stat.level_dps / is_static / valid / changed / e_ac / ac_bypass
 *    门控：本函数写 gate->is_static 与 gate->rollback_granules，供**下一帧**的处理函数 1 读取
 *
 *    ★ 启动阶段旁路（能量 + 交流判据，常量见 v5f_tune.h 的 V5F_DET_AC_*）：
 *      主路是**直流**判据，且阈值表索引来自"累积静止证据"，而证据只在主路判静止时累加
 *      —— 上电零偏残差一旦超过表的上限 3*base = 0.3246 dps 就形成闭环并**永久锁死**
 *      （实测 20260914_233341：DC 0.528 dps，q 恒 (1,0,0,0)，整条链不动）。
 *      旁路用**交流能量**（三轴滑窗方差之和，对直流零偏完全不可见）替代受零偏污染的
 *      直流均值来认"静止"，并用**总能量**上限挡住恒定速率的真转动（恒定速率没有交流量）。
 *      旁路只在 imu.bias_ok 锁存前参与，且只做"或"：只能把主路的"运动"改判成"静止"。
 *      实测两者分离度：静止 e_ac 0.048~0.057、运动 0.37~84 dps^2（阈值 0.20）。 */
uint8_t v5f_proc_static_detect(volatile v5f_hold_t *h, volatile v5f_proc_gate_t *gate);

/* 3) 姿态四元数（陀螺积分，吃前一项的补偿结果）
 *    输入 h->imu.gyro_dps[]（处理函数 1 输出，零偏 + 逐轴标度系数已载入）；
 *    递推 q ← q × dq，dq 由本帧机体角速度与 dt 构造（半角一阶近似）；每帧归一化。
 *    约定：q = {w, x, y, z}，右手系，q 为 机体 → 导航 的旋转；
 *          机体轴即陀螺自身 x/y/z 轴（与逐轴标度同序）。
 *    参考系：导航系**用重力初始化成竖直**（z = 上），不取上电姿态。第一个"可信重力方向"
 *          帧（acc_valid + 判静止 + |accel_g| 在 1 g ±2% 内）用最小旋转把机体系测到的"上"
 *          转到 (0,0,1)，同时置 up_ref = (0,0,1)、up_ref_ok = 1，并**立即开始积分**。
 *          ★ 不依赖 h->imu.bias_ok：实测把它当使能门会让上电后前 3 s（累计静止满
 *            3τ_boot）q 恒为单位四元数 —— 倾斜上电那 3 s 根本没转到重力系，且
 *            up_ref_ok = 0 会让处理函数 4/5 整段冻结。零偏未收敛的角度误差上界只有
 *            e0*窗口时长（最坏 0.035 dps × 3 s = 0.03 deg），远小于倾角环稳态误差。
 *            bias_ok 现在只作观察标志上报。
 *    结果字段：h->att.q[4] / valid（corr_valid = 0 或未收敛时 valid = 0，
 *              但 q 仍发布当前值，方便观察）。 */
uint8_t v5f_proc_attitude(volatile v5f_hold_t *h,
                            const volatile v5f_proc_gate_t *gate);

/* 4) 加速度计标定（零偏 + 逐轴标度；不依赖前 3 项的任何结果）
 *    输入 h->imu.accel_lsb[]（DMA 原始 LSB，±16 g），输出比力 h->imu.accel_g[]，单位 g。
 *    公式 g[i] = (accel_lsb[i] - b[i]) / S[i]；常数与来源见上面的"传感器定标：加速度计"。
 *    本函数不读 corr_valid：标定只作用在原始 LSB 上，与陀螺链是否报错无关。
 *    结果字段：h->imu.accel_g[3] / acc_valid
 *    另外：up_ref（世界竖直在导航系里的表示）**不再由本函数锁存** —— 导航系已由处理
 *    函数 3 用重力定成竖直，up_ref 恒为 (0,0,1)，由处理函数 3 在使能那一帧置好。
 *    注：accel_g 是**比力**（specific force），静止时大小 1 g、方向 = -重力方向，
 *        不是线性加速度。去重力（减 R(q)^T*up_ref）留给后续处理函数。 */
uint8_t v5f_proc_accel_cal(volatile v5f_hold_t *h,
                            const volatile v5f_proc_gate_t *gate);

/* 5) 世界系速度（比力积分 + 时刻向 0 衰减）
 *    输入 h->imu.accel_g[]（比力，g）、h->att.q[]、h->att.up_ref[]（= 导航系竖直 (0,0,1)）；
 *    每帧**先无条件衰减** v *= (1 - dt/tau_v)，再 a_nav = V5F_VEL_G_LOCAL*(R(q)*accel_g
 *    - up_ref)、v += a_nav*dt（仅 att.valid 且 up_ref_ok 的帧积分）。
 *    **没有 ZUPT、也没有任何速度归零门**：消偏置全靠连续衰减（见 V5F_VEL_DECAY_*）。
 *    只出速度不出位置：位置是速度的二次积分、误差跨锚点累积，本固件不出位置。
 *    结果字段：h->vel.v_nav[3] / valid / age_s */
uint8_t v5f_proc_acc_gate(volatile v5f_hold_t *h, volatile v5f_proc_gate_t *gate);
uint8_t v5f_proc_velocity(volatile v5f_hold_t *h,
                            const volatile v5f_proc_gate_t *gate);

/* 7) 导航 EKF（16 维误差状态，影子模式；**新建文件** proc_ekf.c）
 *    输入：imu.gyro_lsb / accel_lsb（**原始**，只套离线标定常量 —— 不用被在线牵引
 *          改过的 gyro_dps / accel_g，否则零偏状态与旧牵引环互相污染且不可辨识）、
 *          att.q（只在**一次性对齐**那一帧用）、mag.f、baro.press_avg、gps_rmc/gga/gsa/gsv、
 *          以及**上一帧**第 8 步写下的七道门；
 *    输出：h->ekf.*（p / v / q / a_nav / ba / bg / b_baro / 各 1sigma / NIS / gate_bits）。
 *    频率：每 V5F_EKF_DECIM(16) 帧一步 = 501.4 Hz；F P F^T 按行摊到那 16 帧里做，
 *          单帧新增约 512 flops，避免把 ISR 顶出 124.7 us 的预算。
 *    失败/越界时返回 V5F_PROC_ERR_TICK 之外的值：本函数只报 V5F_PROC_OK。 */
uint8_t v5f_proc_ekf(volatile v5f_hold_t *h, const volatile v5f_proc_gate_t *gate);

/* 8) EKF 各观测的**外部门控**（下游写、上游下一帧读）
 *    读最新传感器量，写 gate->ekf_* 七个字段与 ENU 原点（首个有效定位那一帧建立）。
 *    与第 5 步（加速度牵引门）完全同构：门永远由下游算，绝不在环内部现算。 */
uint8_t v5f_proc_ekf_gate(volatile v5f_hold_t *h, volatile v5f_proc_gate_t *gate);

