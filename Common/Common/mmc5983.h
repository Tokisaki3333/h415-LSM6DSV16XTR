/*******************************************************************************
 * mmc5983.h —— MMC5983MA 三轴磁传感器（SPI1，CS=PE0，DRDY=PE1）
 * 寄存器定义见 mmc5983ma_reg.h。
 *
 * 当前主流程只用到 MMC_Init / MMC_ClearLatch / MMC_Enable。
 * 标定与实验性的批量采集接口已随其依赖（justfloat）一起归档到
 * _archive/legacy_disabled_features/。
 *
 * 器件关键行为（已核对手册并实测）：
 *   - 18bit 无符号原始值，每轴 16384 counts/G，理想零点 131072 counts
 *   - INT 引脚高有效且电平锁存：只能靠"写 1 到 Status"清除，
 *     读走数据寄存器不清它。所以每拍读完必须清锁存，否则再无上升沿。
 *   - CTRL0/CTRL1/CTRL2/CTRL3 均为只写寄存器，禁止读-改-读。
 *******************************************************************************/

#ifndef __MMC5983_H
#define __MMC5983_H

#include <stdint.h>

#include "ch32h417.h"

/*==============================================================================
 * 常量
 *============================================================================*/

/* SET/RESET 脉冲之后、触发测量之前的等待。
 * 手册 P15：Set/Reset 电流只走 500ns，且该位在操作结束时自清，无额外等待要求。
 * 按手册值加 4 倍余量取 2us —— 这个值会用在中断里，不能取大。 */
#define MMC_RST_PULSE_WAIT_US   2u

/* 自动周期 SET 档位（CTRL2 bit6:4 Prd_set），编码即"每 N 次测量做一次 SET" */
#define MMC_PRD_SET_1       0x00u
#define MMC_PRD_SET_100     0x30u
#define MMC_PRD_SET_1000    0x60u
#define MMC_PRD_SET_EN      0x80u   /* CTRL2 bit7 En_prd_set */

/*==============================================================================
 * 返回值
 *============================================================================*/
#define MMC_OK                  0
#define MMC_ERR_PARAM          (-1)
#define MMC_ERR_NO_ID          (-2)     /* Product ID 不符 */
#define MMC_ERR_OTP_TIMEOUT    (-3)     /* 等 OTP 就绪超时 */
#define MMC_ERR_SPI            (-4)

/*==============================================================================
 * 数据结构
 *============================================================================*/
typedef struct
{
    uint32_t x;             /* 18bit 无符号原始值 */
    uint32_t y;
    uint32_t z;
} MMC_RawXYZ;

/*==============================================================================
 * 接口
 *============================================================================*/

/* 上电复位到干净态 -> 校验 Product ID -> 配置 CTRL0/1/2/3。
 * 内部对 SW_RST 做有界重试：器件可能带着上次运行的残留完成标志启动，
 * 单次复位未必到位（实测首轮 Status 仍为 0x11），重试到只剩 OTP_Rd_Done 为止。
 * 本函数不启动测量（CMM_EN=0），因此不产生 INT。 */
int MMC_Init(void);

/* 启动连续转换（CTRL2.CMM_EN=1 + 自动 SET）。
 * 必须在 EXTI 使能之后调用，否则第一次完成产生的上升沿会丢。 */
int MMC_Enable(void);

/* 写 1 到 Status 清 INT 锁存，让 PE1 回低。
 * 必须在启动转换之前调用：INT 是锁存型，引脚已经是高就不会再有 0→1 边沿。 */
int MMC_ClearLatch(void);

#endif /* __MMC5983_H */
